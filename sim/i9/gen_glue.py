#!/usr/bin/env python3
"""Copy PSX.sv's own NVRAM glue into include files for the issue #9 bench.

The bench (tb_cj.sv) runs these blocks exactly as PSX.sv has them, with and
without GNET_CARD_JOURNAL:
  glue_decl.svh    the journal wire declarations (GNET_CARD_JOURNAL block)
  glue_loader.svh  the clk_1x loader block (zn_ld_*, zn_card_dl_*, card wait)
  glue_req.svh     the EEPROM NVRAM save request block, the journal request
                   and the gnet_card_journal instance

  sim/i9/gen_glue.py <PSX.sv> <outdir>
"""
import sys
from pathlib import Path


def cut(text, start, end, what):
    i = text.find(start)
    if i < 0 or text.find(start, i + 1) >= 0:
        sys.exit(f'gen_glue: start of {what} not found once')
    j = text.find(end, i)
    if j < 0:
        sys.exit(f'gen_glue: end of {what} not found')
    return text[i:j + len(end)]


src = Path(sys.argv[1]).read_text()
out = Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)

decl = cut(src, '`ifdef GNET_CARD_JOURNAL\n// G-NET: card hunk journal (issue #9',
           'wire [63:0] cj_rd_data;\n`endif\n', 'journal declarations')
loader = cut(src, 'always @(posedge clk_1x) begin\n\tzn_ld_wr      <= 0;',
             '\tzn_card_wait <= zn_card_dl_wr | zn_card_dl_busy;\nend\n', 'loader block')
req = cut(src, '// EEPROM NVRAM save (docs/m4_shell.md 4).',
          '\t.overflow()\n);\n`endif\n', 'request block')

(out / 'glue_decl.svh').write_text('// generated by sim/i9/gen_glue.py from PSX.sv\n' + decl)
(out / 'glue_loader.svh').write_text('// generated by sim/i9/gen_glue.py from PSX.sv\n' + loader)
(out / 'glue_req.svh').write_text('// generated by sim/i9/gen_glue.py from PSX.sv\n' + req)
print('gen_glue: decl %d, loader %d, request %d lines' % (decl.count('\n'), loader.count('\n'), req.count('\n')))
