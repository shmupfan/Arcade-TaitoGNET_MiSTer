#!/usr/bin/env python3
"""Copy PSX.sv's own high score and NVRAM glue into include files for the bench.

The bench (tb_hs.sv) runs these blocks exactly as PSX.sv has them, with and
without GNET_HISCORE:
  glue_decl.svh    the GNET_HISCORE wire declarations
  glue_loader.svh  the clk_1x loader block (zn_ld_*, zn_card_dl_*, card wait)
  glue_req.svh     the EEPROM NVRAM save request block
  glue_inst.svh    the isPaused synchroniser and the gnet_hiscore instance
  glue_ch3.svh     channel 3: the cdc_handshake from clk_1x and zn2_ch3_arb
                   (GNET_CPU50 with GNET_ZN2), parameter overrides removed
                   for the GHDL netlist of cdc_handshake (64/32 bits built in)

  sim/hiscore/gen_glue.py <PSX.sv> <outdir>
"""
import sys
from pathlib import Path


def cut(text, start, end, what):
    i = text.find(start)
    if i < 0 or text.find(start, i + 1) >= 0:
        sys.exit(f'gen_glue: start of {what} not found once')
    j = text.find(end, i)
    if j < 0:
        sys.exit(f'gen_glue: end of {what} not found')
    return text[i:j + len(end)]


src = Path(sys.argv[1]).read_text()
out = Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)

parts = {
    'glue_decl.svh': cut(src, "`ifdef GNET_HISCORE\n// High score save from MAME's hiscore.dat",
                         "wire [31:0] ch3_rsp;          // channel 3 crossing response (reads)\n`endif\n",
                         'declarations'),
    'glue_loader.svh': cut(src, 'always @(posedge clk_1x) begin\n\tzn_ld_wr      <= 0;',
                           '\tzn_card_wait <= zn_card_dl_wr | zn_card_dl_busy;\nend\n', 'loader block'),
    'glue_req.svh': cut(src, '// EEPROM NVRAM save (docs/m4_shell.md 4).',
                        "\t\tnv_dirty      <= 1'b0;\n\tend\nend\n", 'request block'),
    'glue_inst.svh': cut(src, "`ifdef GNET_HISCORE\n// G-NET: high score save (rtl/gnet/gnet_hiscore.sv",
                         "\t.m_rdata(ch3_rsp)\n);\n`endif\n", 'hiscore instance'),
    'glue_ch3.svh': cut(src, 'wire [26:0] ch3h_addr;', 'assign zn_fl_dout = ch3c_dout;\n', 'channel 3 block'),
}
ch3 = parts['glue_ch3.svh']
n = ch3.count('cdc_handshake #(.REQ_W(64), .RSP_W(32)) ch3_cdc')
if n != 1:
    sys.exit(f'gen_glue: channel 3 crossing instance found {n} times')
parts['glue_ch3.svh'] = ch3.replace('cdc_handshake #(.REQ_W(64), .RSP_W(32)) ch3_cdc', 'cdc_handshake ch3_cdc')
for name, text in parts.items():
    (out / name).write_text('// generated by sim/hiscore/gen_glue.py from PSX.sv\n' + text)
print('gen_glue: ' + ', '.join('%s %d' % (k, v.count('\n')) for k, v in parts.items()))
